package SpringCore.lifecycle;

public class Pepsi   {

    private double price;

    public Pepsi() {}

    public double getPrice() {
        return price;
    }

    public void setPrice(double price) {
        this.price = price;
    }

    @Override
    public String toString() {
        return "Pepsi{" +
                "price=" + price +
                '}';
    }
}
